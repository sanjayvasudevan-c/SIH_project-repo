const cell = (s) => String(s ?? '').replace(/\|/g, '\\|');
const f2 = (n) => (isNum(n) ? String(Math.round(n * 1000) / 1000) : '');

function candidateTable(rows) {
  const out = ['| Officer | Tier | Eligible | Excluded by | Open points | Capacity | Utilisation after this task | Score | Chosen |', '|---|---:|---|---|---:|---:|---:|---:|---|'];
  for (const c of rows) out.push(`| ${cell(c.name)} | ${c.tier} | ${c.eligible ? 'yes' : 'no'} | ${cell(c.excludedBy ?? '')} | ${f2(c.openPoints)} | ${f2(c.capacity)} | ${f2(c.projectedUtil)} | ${f2(c.score)} | ${c.chosen ? '**chosen**' : ''} |`);
  return out.join('\n');
}

export function workedExample(src) {
  const { snap, manifest } = src;
  const out = [GEN, '', '# Worked example: how the assignment engine decided', '', '[← Assignment charts](README.md) · [Evidence visualizations](../README.md)', '',
    `Two real decisions from the snapshot (${manifest.generatedAt.slice(0, 10)}, commit \`${manifest.commit.short}\`), copied from the Evidence API\'s \`assignment-trace\` responses in [\`data/\`](../data/). The candidate tables and the reason text are the engine\'s own stored record of the decision, quoted without editing. The data is synthetic.`, '',
    'How the engine decides (code: [`api/src/assignment/engine.ts`](../../../../api/src/assignment/engine.ts); diagram: [assignment decision flow](../architecture/README.md#assignment-decision-flow)): it filters the candidates of a tier (role, region, skill, availability, barred or recused, capacity), prefers a continuity officer where the task allows it, otherwise picks the lowest load score, moves to the next tier (Bureau overflow) if nobody passes, and records a BLOCKED decision if nobody does.', ''];

  const pickRow = (file, outcome) => (snap[file]?.rows ?? []).find((r) => r.outcome === outcome);
  const asg = pickRow('assignment-trace-assigned', 'ASSIGNED');
  const blk = pickRow('assignment-trace-blocked', 'BLOCKED');
  const section = (n, title, row, file, why) => {
    out.push(`## ${n}. ${title}`, '');
    if (!row) {
      out.push(`**Not available in this snapshot:** ${why}`, '');
      return;
    }
    const chosen = row.candidates.find((c) => c.chosen);
    out.push(`- Task: ${tick(row.taskType)}; decided at ${row.decidedAt}; task weight ${row.weight}; outcome **${row.outcome}**.`, `- Candidates recorded: ${row.candidates.length}; eligible: ${row.candidates.filter((c) => c.eligible).length}; excluded: ${row.candidates.filter((c) => !c.eligible).length}.`, chosen ? `- Chosen: ${chosen.name} (tier ${chosen.tier}).` : '- Chosen: nobody (no assignment exists for this decision).', `- Source: ${tick(`${file}.json`)}, trace id ${row.id}.`, '', '**Stored reason text, verbatim:**', '', quote(row.reasonText), '');
    const excluded = row.candidates.filter((c) => !c.eligible);
    const head = row.candidates.length > 12 ? [...row.candidates].sort((a, b) => Number(b.chosen) - Number(a.chosen) || Number(a.eligible) - Number(b.eligible) || a.score - b.score) : row.candidates;
    if (row.candidates.length > 12) {
      out.push(`Candidate table (all ${row.candidates.length} rows; the chosen officer and the ${excluded.length} excluded first, then the rest by score):`, '', '<details><summary>Show the candidate table</summary>', '', candidateTable(head), '', '</details>', '');
    } else {
      out.push('Candidate table:', '', candidateTable(head), '');
    }
    if (row.outcome === 'ASSIGNED') {
      const cont = /portfolio officer|returning officer/.test(row.reasonText);
      out.push(cont
        ? 'Reading it: the stored reason says this officer was chosen because they are the case\'s continuity officer, which the rules prefer where the officer passes the filters, so the choice does not follow the lowest score in the table.'
        : 'Reading it: among the eligible candidates the engine took the lowest load score.', '');
    } else {
      out.push('Reading it: every candidate in every tier was excluded, so the engine assigned nobody. Per [the workflow diagram notes](../../WORKFLOW.md), a blocked task records a BLOCKED flag, an audit row and a notice for the region head, and appears in the manual-assignment queue.', '');
    }
  };
  section(1, 'An assigned decision', asg, 'assignment-trace-assigned', 'no assigned decision is in the snapshot.');
  section(2, 'A blocked decision', blk, 'assignment-trace-blocked', 'this dataset recorded no blocked decision.');

  const rows = snap.assignment?.data?.continuityOverrides?.rows ?? [];
  out.push('## 3. The officer above the normal cap', '');
  if (!rows.length) out.push('No officer is above their cap in this snapshot.', '');
  else {
    out.push(`${rows.length === 1 ? 'One officer is' : `${rows.length} officers are`} above the normal cap of ${rows[0].normalCap.toFixed(2)}. The stored explanation, verbatim:`, '');
    for (const r of rows) out.push(quote(r.text), '');
    const sameAsChosen = asg && rows.some((r) => r.officerId === asg.chosenOfficerId);
    if (sameAsChosen) out.push('This is the same officer who was chosen in the first example. At the time of that decision their utilisation after the task was well under the cap (see the table); the explanation above says the decision table does not record which of the possible causes applies now.', '');
    out.push('Source: `continuityOverrides` in [`data/assignment.json`](../data/assignment.json).', '');
  }
  out.push('---', '', '[← Assignment charts](README.md)', '');
  return out.join('\n');
}
